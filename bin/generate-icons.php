<?php
/**
 * Writes data/lucide-icons.php from unpacked lucide-static and, optionally, @lucide/lab packages:
 *
 *     npm pack lucide-static@<version> @lucide/lab@<version>
 *     mkdir core lab && tar -xzf lucide-static-*.tgz -C core && tar -xzf lucide-lab-*.tgz -C lab
 *     php bin/generate-icons.php core/package lab/package
 *
 * One file of name => inner SVG markup, so a page inlines the icons it uses and opcache keeps the
 * set in memory; aliases are kept, since they are names people use. Lab icons (lucide.dev/icons/lab)
 * share the namespace; where a name exists in both, the main set wins.
 */

// A CLI tool: var_export() writes the data file, nothing is debug output.
// phpcs:disable WordPress.PHP.DevelopmentFunctions.error_log_var_export

/** @param list<string> $argv */
function bp_ui_generate_icons( array $argv ): int {
	$meta = bp_ui_package( $argv[1] ?? '', 'lucide-static' );
	$lab  = isset( $argv[2] ) ? bp_ui_package( $argv[2], '@lucide/lab' ) : null;
	if ( null === $meta || ( isset( $argv[2] ) && null === $lab ) ) {
		fwrite( STDERR, "Usage: php bin/generate-icons.php <unpacked lucide-static> [<unpacked @lucide/lab>]\n" );
		return 1;
	}

	$icons = bp_ui_read_icons( $meta['dir'] );
	if ( is_int( $icons ) ) {
		return $icons;
	}
	$skipped = 0;
	if ( null !== $lab ) {
		$lab_icons = bp_ui_read_icons( $lab['dir'] );
		if ( is_int( $lab_icons ) ) {
			return $lab_icons;
		}
		$skipped = count( array_intersect_key( $lab_icons, $icons ) );
		$icons  += $lab_icons;
	}
	ksort( $icons );

	$out = "<?php\n// Generated by bin/generate-icons.php from lucide-static {$meta['version']}" . ( null === $lab ? '' : " and @lucide/lab {$lab['version']}" ) . " (ISC); do not edit.\nreturn [\n\t'version'     => " . var_export( $meta['version'], true ) . ",\n\t'lab_version' => " . var_export( $lab['version'] ?? null, true ) . ",\n\t'icons'       => [\n";
	foreach ( $icons as $name => $inner ) {
		$out .= "\t\t" . var_export( $name, true ) . ' => ' . var_export( $inner, true ) . ",\n";
	}
	$out .= "\t],\n];\n";

	file_put_contents( dirname( __DIR__ ) . '/data/lucide-icons.php', $out );
	printf( "%d icons from lucide-static %s%s; %d lab names already in the main set\n", count( $icons ), $meta['version'], null === $lab ? '' : " and @lucide/lab {$lab['version']}", $skipped );

	return 0;
}

/** @return array{dir: string, version: string}|null */
function bp_ui_package( string $dir, string $name ): ?array {
	$dir  = rtrim( $dir, '/' );
	$meta = is_readable( "{$dir}/package.json" ) ? json_decode( (string) file_get_contents( "{$dir}/package.json" ), true ) : null;

	if ( ! is_array( $meta ) || ( $meta['name'] ?? '' ) !== $name ) {
		return null;
	}

	return [
		'dir'     => $dir,
		'version' => (string) $meta['version'],
	];
}

/** @return array<string, string>|int Name => inner markup, or an exit code. */
function bp_ui_read_icons( string $source ): array|int {
	$icons = [];
	foreach ( glob( "{$source}/icons/*.svg" ) as $file ) {
		$svg = (string) file_get_contents( $file );
		if ( ! preg_match( '#<svg[^>]*>(.*)</svg>#s', $svg, $match ) ) {
			fwrite( STDERR, "No <svg> in {$file}\n" );
			return 1;
		}
		$inner = trim( (string) preg_replace( '/\s+/', ' ', $match[1] ) );
		$inner = str_replace( [ ' />', '> <' ], [ '/>', '><' ], $inner );
		if ( preg_match( '/<script|on[a-z]+=|javascript:/i', $inner ) ) {
			fwrite( STDERR, "Refusing {$file}: it holds script\n" );
			return 1;
		}
		$icons[ basename( $file, '.svg' ) ] = $inner;
	}

	return $icons;
}

exit( bp_ui_generate_icons( $argv ) );
