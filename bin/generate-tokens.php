<?php
/**
 * Writes assets/tokens.css from tokens.json, the one source of the design tokens:
 *
 *     php bin/generate-tokens.php
 *
 * tokens.json uses the Design System artifact's format (lists of {name, value, usage}), so a
 * project's style guide reads the same file. Each token becomes a `--<name>` variable on :root;
 * a colour's `wpAdmin` value replaces it in wp-admin, where the user's admin colour applies;
 * motion durations drop to 0 under prefers-reduced-motion.
 */

function bp_ui_generate_tokens(): int {
	$root   = dirname( __DIR__ );
	$tokens = json_decode( (string) file_get_contents( "{$root}/tokens.json" ), true );
	if ( ! is_array( $tokens ) ) {
		fwrite( STDERR, "tokens.json is not valid JSON\n" );
		return 1;
	}

	$vars  = [];
	$admin = [];
	foreach ( $tokens['color']['tokens'] as $token ) {
		$vars[ $token['name'] ] = $token['value'];
		if ( isset( $token['wpAdmin'] ) ) {
			$admin[ $token['name'] ] = $token['wpAdmin'];
		}
	}
	foreach ( $tokens['type']['families'] as $key => $stack ) {
		$vars[ "bp-font-{$key}" ] = $stack;
	}
	foreach ( [ 'fontSize', 'spacing', 'size', 'radius', 'shadow', 'duration', 'easing' ] as $family ) {
		foreach ( $tokens[ $family ]['tokens'] ?? [] as $token ) {
			$vars[ $token['name'] ] = $token['value'];
		}
	}

	foreach ( array_merge( $vars, $admin ) as $name => $value ) {
		if ( 1 !== preg_match( '/^bp-[a-z0-9-]+$/', $name ) || preg_match( '/[;{}<>]/', (string) $value ) ) {
			fwrite( STDERR, "Refusing token {$name}\n" );
			return 1;
		}
	}

	$css = "/* Generated by bin/generate-tokens.php from tokens.json ({$tokens['name']} tokens); do not edit. */\n\n:root {\n";
	foreach ( $vars as $name => $value ) {
		$css .= "\t--{$name}: {$value};\n";
	}
	$css .= "}\n\n/* In wp-admin the action colour is the user's admin colour scheme. */\nbody.wp-admin {\n";
	foreach ( $admin as $name => $value ) {
		$css .= "\t--{$name}: {$value};\n";
	}
	$css .= "}\n\n@media (prefers-reduced-motion: reduce) {\n\t:root {\n";
	foreach ( $tokens['duration']['tokens'] ?? [] as $token ) {
		$css .= "\t\t--{$token['name']}: 0s;\n";
	}
	$css .= "\t}\n}\n";

	file_put_contents( "{$root}/assets/tokens.css", $css );
	printf( "%d tokens, %d with a wp-admin value\n", count( $vars ), count( $admin ) );

	return 0;
}

exit( bp_ui_generate_tokens() );
